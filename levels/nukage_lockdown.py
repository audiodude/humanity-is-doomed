def shutter(name, box, tag, *, floor, flat, track):
    """A lockdown shutter 128 wide, opened only by `tag`. SPCDOOR3 is a
    64-wide picture, so each long face is split in two at its midpoint. One
    sector, not two halves: two doors side by side would each open only to
    the other's closed ceiling."""
    x1, y1, x2, y2 = box
    if x2 - x1 == 128:
        xm = x1 + 64
        loop = [(x1, y1), (xm, y1), (x2, y1), (x2, y2), (xm, y2), (x1, y2)]
    else:
        ym = y1 + 64
        loop = [(x1, y1), (x2, y1), (x2, ym), (x2, y2), (x1, y2), (x1, ym)]
    return [door(name, loop, face="SPCDOOR3", track=track, tag=tag, floor=floor, flat=flat)]


