def cell(x, y):
    (x1, x2), (y1, y2) = XB[x], YB[y]
    loop = rect(x1, y1, x2, y2)
    pts = NORTH_PTS.get(f"{x}_{y}", [])
    return loop[:3] + [(px, y2) for px in sorted(pts, reverse=True)] + loop[3:]


def block(x, y):
    (x1, x2), (y1, y2) = XB[x], YB[y]
    return rect(x1, y1, x2, y2)


