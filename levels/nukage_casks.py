def jamb_lines(a, b, tex, w=16):
    """The opening's end points and the two jamb segments either side of it."""
    n = dist(a, b)
    ux, uy = round((b[0] - a[0]) * w / n), round((b[1] - a[1]) * w / n)
    a0, b1 = (a[0] - ux, a[1] - uy), (b[0] + ux, b[1] + uy)
    return [a0, a, b, b1], [trim(a0, a, tex), trim(b, b1, tex)]


def with_points(loop, pts):
    """loop with every point of pts that lies on one of its edges inserted."""
    out = []
    for a, b in edges(loop):
        out.append(a)
        out += sorted((p for p in pts if on_segment(p, a, b)), key=lambda p: dist(a, p))
    return out


