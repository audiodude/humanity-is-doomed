# Shaft (inner octagon) and outer wall, CCW from the east face; segment k
# runs from vertex k to k+1: 0 E, 1 NE, 2 N, 3 NW, 4 W, 5 SW, 6 S, 7 SE.
INNER = [(320, -128), (320, 128), (128, 320), (-128, 320), (-320, 128), (-320, -128), (-128, -320), (128, -320)]
OUTER = [(2 * x, 2 * y) for x, y in INNER]


def P(k, t, r):
    """Point in segment k: t along it (0..1, CCW), r from shaft (0) to outer wall (1)."""
    t, r = F(t), F(r)
    a, b = INNER[k], INNER[(k + 1) % 8]
    c, d = OUTER[k], OUTER[(k + 1) % 8]
    ix, iy = a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t
    ox, oy = c[0] + (d[0] - c[0]) * t, c[1] + (d[1] - c[1]) * t
    x, y = ix + (ox - ix) * r, iy + (oy - iy) * r
    assert x.denominator == 1 and y.denominator == 1, (k, t, r, x, y)
    return int(x), int(y)


def quad(k, t0, t1, r0=0, r1=1):
    return [P(k, t0, r0), P(k, t1, r0), P(k, t1, r1), P(k, t0, r1)]


