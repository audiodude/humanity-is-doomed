def _split_edges(sectors):
    """Insert every sector vertex that lies on another sector's edge into it,
    so lines only meet at shared vertices."""
    from .model import on_segment
    pts = {p for s in sectors for loop in s.loops + s.pillars for p in loop}
    for s in sectors:
        def fix(loop):
            out = []
            for a, b in zip(loop, loop[1:] + loop[:1]):
                out.append(a)
                mids = [p for p in pts if on_segment(p, a, b)]
                mids.sort(key=lambda p: (p[0] - a[0]) ** 2 + (p[1] - a[1]) ** 2)
                out += mids
            return out
        s.loops = [fix(lp) for lp in s.loops]
        s.pillars = [fix(lp) for lp in s.pillars]


