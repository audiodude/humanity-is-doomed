def with_points(loop, pts):
    """loop with every point of pts that lies on one of its edges inserted."""
    out = []
    for a, b in edges(loop):
        out.append(a)
        out += sorted((p for p in pts if on_segment(p, a, b)), key=lambda p: dist(a, p))
    return out


def trim(p, q, tex):
    """A one-sided wall segment (keyed with its sector on the right) in a trim texture."""
    return (p, q), Line(front=Side(mid=tex))


