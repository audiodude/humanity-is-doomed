def door_kw(floor, flat, near, far=None, *, near_d=32, far_d=16, **kw):
    """doorway() arguments for a BIGDOOR2 door in recesses on both sides,
    DOORTRAK all round, so the face is never set flat into a material wall.
    near: the floor flat on the side `at` is on; far: beyond the door."""
    return dict(alcove=near_d, far_alcove=far_d, alcove_wall=kw.pop("alcove_wall", "DOORTRAK"),
                alcove_flat=near, far_flat=far or flat, floor=floor, flat=flat, **kw)


